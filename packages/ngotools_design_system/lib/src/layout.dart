/// Shared layout values for organization apps.
abstract final class NgoToolsLayout {
  /// Compact spacing between closely related elements.
  static const compactSpacing = 8.0;

  /// Default spacing and horizontal screen inset.
  static const spacing = 16.0;

  /// Large spacing between content sections.
  static const sectionSpacing = 24.0;

  /// Standard component corner radius.
  static const cornerRadius = 16.0;

  /// Width at which navigation may move to a rail.
  static const navigationRailBreakpoint = 840.0;
}
